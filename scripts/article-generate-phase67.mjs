import {createHash} from "node:crypto";
import {readFile, writeFile} from "node:fs/promises";
import path from "node:path";

const article = path.join(process.cwd(), "article");
const snapshotPath = path.join(
  article, "data", "phase6-phase7-preliminary.json",
);
const generated = path.join(article, "generated");
const checkOnly = process.argv.includes("--check");

function command(name, value) {
  return `\\newcommand{\\${name}}{${value}}`;
}

async function emit(name, content) {
  const output = path.join(generated, name);
  if (!checkOnly) {
    await writeFile(output, content, "utf8");
    return;
  }
  let current = "";
  try {
    current = await readFile(output, "utf8");
  } catch {
    // A missing generated file is stale.
  }
  if (current !== content) throw new Error(`Stale Phase 6/7 asset: ${name}`);
}

const bytes = await readFile(snapshotPath);
const data = JSON.parse(bytes.toString("utf8"));
if (data.schemaVersion !== 1 || !data.phase6 || !data.phase7) {
  throw new Error("Invalid Phase 6/7 evidence snapshot.");
}
const timedSecond = data.phase6.timed.find(({milliseconds}) => milliseconds === 1000);
const openingEight = data.phase7.opening.find(({workers}) => workers === 8);
const metrics = [
  "% Generated by scripts/article-generate-phase67.mjs.",
  command("PhaseSixSevenSnapshotId", data.snapshotId),
  command("PhaseSixBaselineSelectiveDepth", timedSecond.baselineSelectiveDepthTotal),
  command("PhaseSixCandidateSelectiveDepth", timedSecond.candidateSelectiveDepthTotal),
  command("PhaseSevenOpeningSpeedup", openingEight.speedup.toFixed(2)),
  command("PhaseSevenOpeningEfficiency", (openingEight.efficiency * 100).toFixed(1)),
  command("PhaseSevenRepeatedMoves", openingEight.researches),
  command("PhaseSevenPriorRepeatedMoves", data.phase7.v6OpeningRepeatedMoves),
  "",
].join("\n");
const rows = data.phase7.opening.map((entry) =>
  `${entry.workers} & ${entry.serialMs} & ${entry.scheduledMs} & ` +
  `${entry.speedup.toFixed(2)} & ${(entry.efficiency * 100).toFixed(1)} & ` +
  `${entry.researches} & ${entry.moveParity ? "yes" : "no"} \\\\`,
).join("\n");
const table = `% Generated file.
\\begin{table*}[t]
\\centering
\\caption{Preliminary depth-six seed-first dynamic-root results on the opening.}
\\label{tab:phase-seven-root}
\\scriptsize
\\begin{tabular}{rrrrrrr}
\\toprule
Workers & Serial ms & Scheduled ms & Speedup & Efficiency (\\%) & Re-searches & Parity \\\\
\\midrule
${rows}
\\bottomrule
\\end{tabular}
\\end{table*}
`;
const manifest = `${JSON.stringify({
  schemaVersion: 1,
  generatedBy: "scripts/article-generate-phase67.mjs",
  snapshot: {
    file: path.basename(snapshotPath),
    snapshotId: data.snapshotId,
    status: data.status,
    sha256: createHash("sha256").update(bytes).digest("hex"),
  },
}, null, 2)}\n`;

await emit("phase-six-seven-metrics.tex", metrics);
await emit("phase-seven-root-table.tex", table);
await emit("phase-six-seven-snapshot-manifest.json", manifest);
console.log(`${checkOnly ? "Checked" : "Generated"} Phase 6/7 evidence.`);
