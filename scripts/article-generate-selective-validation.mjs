import {createHash} from "node:crypto";
import {readFile, writeFile} from "node:fs/promises";
import path from "node:path";

const article = path.join(process.cwd(), "article");
const generated = path.join(article, "generated");
const snapshotPath = path.join(
  article,
  "data",
  "selective-validation-preliminary.json",
);
const oneSecondPath = path.join(
  article,
  "data",
  "guarded-lmr-one-second-preliminary.json",
);
const checkOnly = process.argv.includes("--check");

function command(name, value) {
  return `\\newcommand{\\${name}}{${value}}`;
}

async function emit(name, content) {
  const output = path.join(generated, name);
  if (!checkOnly) {
    await writeFile(output, content, "utf8");
    return;
  }
  let current = "";
  try {
    current = await readFile(output, "utf8");
  } catch {
    // A missing generated artifact is stale.
  }
  if (current !== content) throw new Error(`Stale selective asset: ${name}`);
}

const bytes = await readFile(snapshotPath);
const oneSecondBytes = await readFile(oneSecondPath);
const snapshot = JSON.parse(bytes.toString("utf8"));
const oneSecond = JSON.parse(oneSecondBytes.toString("utf8"));
if (snapshot.schemaVersion !== 1 || !snapshot.adaptiveLmr || !snapshot.guardedLmr) {
  throw new Error("Invalid selective-validation evidence snapshot.");
}

if (oneSecond.schemaVersion !== 1 || oneSecond.millisecondsPerMove !== 1000) {
  throw new Error("Invalid one-second evidence snapshot.");
}

const aggressive = snapshot.adaptiveLmr;
const guarded = snapshot.guardedLmr;
const metrics = [
  "% Generated by scripts/article-generate-selective-validation.mjs.",
  command("SelectiveValidationSnapshotId", snapshot.snapshotId),
  command("AggressiveLmrFixedNodeGames", aggressive.fixedNode.games),
  command("AggressiveLmrFixedNodeScore", `${aggressive.fixedNode.candidateWins}--${aggressive.fixedNode.baselineWins}--${aggressive.fixedNode.unresolved}`),
  command("AggressiveLmrRegret", aggressive.rootAudit.candidateTotalRegret),
  command("SelectiveBaselineRegret", aggressive.rootAudit.baselineTotalRegret),
  command("GuardedLmrFixedNodeGames", guarded.fixedNode.games),
  command("GuardedLmrFixedNodeScore", `${guarded.fixedNode.candidateWins}--${guarded.fixedNode.baselineWins}`),
  command("GuardedLmrTimedGames", guarded.fixedTime.games),
  command("GuardedLmrTimedScore", `${guarded.fixedTime.candidateWins}--${guarded.fixedTime.baselineWins}`),
  command("GuardedLmrTimedAveragePlies", guarded.fixedTime.averagePlies.toFixed(2)),
  command("GuardedLmrRegret", guarded.rootAudit.candidateTotalRegret),
  command("GuardedLmrOneSecondGames", oneSecond.games),
  command("GuardedLmrOneSecondScore", `${oneSecond.candidateWins}--${oneSecond.baselineWins}`),
  command("GuardedLmrOneSecondAveragePlies", oneSecond.averagePlies.toFixed(2)),
  command("GuardedLmrOneSecondNps", oneSecond.aggregateNps.toLocaleString("en-US")),
  "",
].join("\n");

const rows = [
  ["adaptive LMR", aggressive],
  ["guarded LMR", guarded],
].map(([name, item]) =>
  `${name} & ${item.fixedNode.games} & ` +
  `${item.fixedNode.candidateWins}--${item.fixedNode.baselineWins}--${item.fixedNode.unresolved} & ` +
  `${item.fixedTime.games} & ` +
  `${item.fixedTime.candidateWins}--${item.fixedTime.baselineWins}--${item.fixedTime.unresolved} & ` +
  `${item.rootAudit.candidateTotalRegret} & ${item.status} \\\\`,
).join("\n");

const table = `% Generated file.
\\begin{table*}[t]
\\centering
\\caption{Selective-search validation. Regret is summed over the same 50-position depth-five audit; lower is better. Both SPRTs remained undecided.}
\\label{tab:selective-validation}
\\scriptsize
\\begin{tabular}{lrrr rrl}
\\toprule
Variant & Fixed-node games & Fixed-node score & 250 ms games & 250 ms score & Regret & Status \\\\
\\midrule
${rows}
\\bottomrule
\\end{tabular}
\\end{table*}
`;

const manifest = JSON.stringify({
  schemaVersion: 1,
  generatedBy: "scripts/article-generate-selective-validation.mjs",
  snapshot: {
    file: path.basename(snapshotPath),
    snapshotId: snapshot.snapshotId,
    status: snapshot.status,
    sha256: createHash("sha256").update(bytes).digest("hex"),
  },
  oneSecondSnapshot: {
    file: path.basename(oneSecondPath),
    snapshotId: oneSecond.snapshotId,
    status: oneSecond.status,
    sha256: createHash("sha256").update(oneSecondBytes).digest("hex"),
  },
}, null, 2) + "\n";

await emit("selective-validation-metrics.tex", metrics);
await emit("selective-validation-table.tex", table);
await emit("selective-validation-snapshot-manifest.json", manifest);
console.log(`${checkOnly ? "Checked" : "Generated"} selective evidence.`);
