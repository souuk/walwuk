import {createHash} from "node:crypto";
import {readFile, writeFile} from "node:fs/promises";
import path from "node:path";

const article = path.join(process.cwd(), "article");
const snapshotPath = path.join(article, "data", "phase5-topology-root-preliminary.json");
const generated = path.join(article, "generated");
const checkOnly = process.argv.includes("--check");

function command(name, value) {
  return `\\newcommand{\\${name}}{${value}}`;
}

async function emit(name, content) {
  const output = path.join(generated, name);
  if (!checkOnly) {
    await writeFile(output, content, "utf8");
    return;
  }
  let current = "";
  try {
    current = await readFile(output, "utf8");
  } catch {
    // A missing generated file is stale.
  }
  if (current !== content) throw new Error(`Stale Phase Five asset: ${name}`);
}

const bytes = await readFile(snapshotPath);
const data = JSON.parse(bytes.toString("utf8"));
if (data.schemaVersion !== 1 || !data.topologyV4 || !data.dynamicRootV6) {
  throw new Error("Invalid Phase Five evidence snapshot.");
}
const topology = data.topologyV4;
const dynamic = data.dynamicRootV6;
const opening = dynamic.positions.find(({name}) => name === "opening");
const metrics = [
  "% Generated by scripts/article-generate-phase5.mjs.",
  command("PhaseFiveSnapshotId", data.snapshotId),
  command("TopologyVFourBaselineNps", topology.milliseconds1000.baselineNps.toLocaleString("en-US")),
  command("TopologyVFourCandidateNps", topology.milliseconds1000.candidateNps.toLocaleString("en-US")),
  command("TopologyVFourBaselineDepth", topology.milliseconds1000.baselineDepth.toFixed(2)),
  command("TopologyVFourCandidateDepth", topology.milliseconds1000.candidateDepth.toFixed(2)),
  command("DynamicRootOpeningSpeedup", opening.speedup.toFixed(2)),
  command("DynamicRootOpeningEfficiency", (opening.efficiency * 100).toFixed(1)),
  command("DynamicRootWorkers", dynamic.eligibleWorkers),
  "",
].join("\n");
const rows = dynamic.positions.map((entry) =>
  `${entry.name} & ${entry.mode} & ${entry.serialMs} & ${entry.scheduledMs} & ` +
  `${entry.speedup.toFixed(2)} & ${entry.moveParity ? "yes" : "no"} \\\\`,
).join("\n");
const table = `% Generated file.
\\begin{table*}[t]
\\centering
\\caption{Preliminary depth-six guarded dynamic-root results. Unstable positions use the exact serial fallback.}
\\label{tab:phase-five-root}
\\scriptsize
\\begin{tabular}{llrrrr}
\\toprule
Position & Mode & Serial ms & Scheduled ms & Speedup & Move parity \\\\
\\midrule
${rows}
\\bottomrule
\\end{tabular}
\\end{table*}
`;
const manifest = JSON.stringify({
  schemaVersion: 1,
  generatedBy: "scripts/article-generate-phase5.mjs",
  snapshot: {
    file: path.basename(snapshotPath),
    snapshotId: data.snapshotId,
    status: data.status,
    sha256: createHash("sha256").update(bytes).digest("hex"),
  },
}, null, 2) + "\n";

await emit("phase-five-metrics.tex", metrics);
await emit("phase-five-root-table.tex", table);
await emit("phase-five-snapshot-manifest.json", manifest);
console.log(`${checkOnly ? "Checked" : "Generated"} Phase Five evidence.`);
