import {createHash} from "node:crypto";
import {readFile, writeFile} from "node:fs/promises";
import path from "node:path";

const article = path.join(process.cwd(), "article");
const snapshotPath = path.join(
  article, "data", "phase8-phase9-preliminary.json",
);
const generated = path.join(article, "generated");
const checkOnly = process.argv.includes("--check");
const command = (name, value) => `\\newcommand{\\${name}}{${value}}`;
async function emit(name, content) {
  const output = path.join(generated, name);
  if (!checkOnly) return writeFile(output, content, "utf8");
  let current = "";
  try {
    current = await readFile(output, "utf8");
  } catch {
    // Missing generated output is stale.
  }
  if (current !== content) throw new Error(`Stale Phase 8/9 asset: ${name}`);
}

const bytes = await readFile(snapshotPath);
const data = JSON.parse(bytes.toString("utf8"));
const two = data.phase8.summaries["2"];
const four = data.phase8.summaries["4"];
const eight = data.phase8.summaries["8"];
const win = data.phase9.proofs.find(({outcome}) => outcome === "win");
const loss = data.phase9.proofs.find(({outcome}) => outcome === "loss");
const metrics = [
  "% Generated by scripts/article-generate-phase89.mjs.",
  command("PhaseEightTwoSpeedup", two.medianSpeedup.toFixed(2)),
  command("PhaseEightTwoEfficiency", (two.parallelEfficiency * 100).toFixed(1)),
  command("PhaseEightEightSpeedup", eight.medianSpeedup.toFixed(2)),
  command("PhaseEightEightEfficiency", (eight.parallelEfficiency * 100).toFixed(1)),
  command("PhaseNineWinStates", win.states),
  command("PhaseNineWinDepth", win.certificateDepth),
  command("PhaseNineLossStates", loss.states),
  command("PhaseNineLossDepth", loss.certificateDepth),
  "",
].join("\n");
const summaries = [[2, two], [4, four], [8, eight]];
const rows = summaries.map(([threads, entry]) =>
  `${threads} & ${entry.medianSpeedup.toFixed(2)} & ` +
  `${(entry.parallelEfficiency * 100).toFixed(1)} \\\\`,
).join("\n");
const table = `% Generated file.
\\begin{table}[t]
\\centering
\\caption{Preliminary shared-TT Wasm root-search scaling at depth four.}
\\label{tab:phase-eight-shared}
\\begin{tabular}{rrr}
\\toprule
Threads & Speedup & Efficiency (\\%) \\\\
\\midrule
${rows}
\\bottomrule
\\end{tabular}
\\end{table}
`;
const manifest = `${JSON.stringify({
  schemaVersion: 1,
  generatedBy: "scripts/article-generate-phase89.mjs",
  snapshot: {
    file: path.basename(snapshotPath),
    snapshotId: data.snapshotId,
    status: data.status,
    sha256: createHash("sha256").update(bytes).digest("hex"),
  },
}, null, 2)}\n`;
await emit("phase-eight-nine-metrics.tex", metrics);
await emit("phase-eight-shared-table.tex", table);
await emit("phase-eight-nine-snapshot-manifest.json", manifest);
console.log(`${checkOnly ? "Checked" : "Generated"} Phase 8/9 evidence.`);
