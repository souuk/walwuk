import {createHash} from "node:crypto";
import {readFile, writeFile} from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const article = path.join(root, "article");
const generated = path.join(article, "generated");
const snapshotPath = path.join(
  article,
  "data",
  "phase3-tranche1-preliminary.json",
);
const checkOnly = process.argv.includes("--check");

function tex(value) {
  return String(value)
      .replaceAll("\\", "\\textbackslash{}")
      .replaceAll("&", "\\&")
      .replaceAll("%", "\\%")
      .replaceAll("_", "\\_")
      .replaceAll("#", "\\#")
      .replaceAll("$", "\\$");
}

function command(name, value) {
  return `\\newcommand{\\${name}}{${value}}`;
}

async function emit(name, content) {
  const output = path.join(generated, name);
  if (!checkOnly) {
    await writeFile(output, content, "utf8");
    return;
  }
  let current = "";
  try {
    current = await readFile(output, "utf8");
  } catch {
    // Report a missing generated file as stale below.
  }
  if (current !== content) throw new Error(`Stale Phase Three asset: ${name}`);
}

const bytes = await readFile(snapshotPath);
const snapshot = JSON.parse(bytes.toString("utf8"));
if (snapshot.schemaVersion !== 1 || !snapshot.snapshotId || !snapshot.phaseThree) {
  throw new Error("Invalid Phase Three evidence snapshot.");
}

const pruning = snapshot.phaseThree.pruning;
const metrics = [
  "% Generated by scripts/article-generate-phase3.mjs. Do not edit.",
  command("PhaseThreeSnapshotId", tex(snapshot.snapshotId)),
  command("PhaseThreeProbCutWins", pruning.probCut.candidateWins),
  command("PhaseThreeProbCutBaselineWins", pruning.probCut.baselineWins),
  command("PhaseThreeProbCutDepth", pruning.probCut.candidateAverageDepth.toFixed(2)),
  command("PhaseThreeProbCutBaselineDepth", pruning.probCut.baselineAverageDepth.toFixed(2)),
  command("PhaseThreeMultiCutWins", pruning.multiCut.candidateWins),
  command("PhaseThreeMultiCutBaselineWins", pruning.multiCut.baselineWins),
  command("PhaseThreeMultiCutDepth", pruning.multiCut.candidateAverageDepth.toFixed(2)),
  command("PhaseThreeMultiCutBaselineDepth", pruning.multiCut.baselineAverageDepth.toFixed(2)),
  command("PhaseThreeAdaptiveLmrGames", pruning.adaptiveLmr.games),
  command("PhaseThreeAdaptiveLmrWins", pruning.adaptiveLmr.candidateWins),
  command("PhaseThreeAdaptiveLmrBaselineWins", pruning.adaptiveLmr.baselineWins),
  command("PhaseThreeAdaptiveLmrDepth", pruning.adaptiveLmr.candidateAverageDepth.toFixed(2)),
  command("PhaseThreeAdaptiveLmrBaselineDepth", pruning.adaptiveLmr.baselineAverageDepth.toFixed(2)),
  command("PhaseThreeParityRandom", snapshot.phaseThree.validation.randomPositions),
  "",
].join("\n");

const rows = Object.values(pruning).map((entry) =>
  `${tex(entry.name)} & ${entry.games} & ${entry.candidateWins} & ` +
  `${entry.baselineWins} & ${entry.unresolved} & ` +
  `${entry.candidateAverageDepth.toFixed(2)} & ` +
  `${entry.baselineAverageDepth.toFixed(2)} & ${tex(entry.status)} \\\\`,
).join("\n");
const table = `% Generated file.
\\begin{table*}[t]
\\centering
\\caption{Preliminary Phase Three fixed-node pruning screens. Each move received 50,000 nodes.}
\\label{tab:phase-three-pruning}
\\scriptsize
\\begin{tabular}{lrrrrrrl}
\\toprule
Candidate & Games & Cand. & Base & Unres. & Cand. depth & Base depth & Status \\\\
\\midrule
${rows}
\\bottomrule
\\end{tabular}
\\end{table*}
`;

const manifest = JSON.stringify({
  schemaVersion: 1,
  generatedBy: "scripts/article-generate-phase3.mjs",
  snapshot: {
    file: path.basename(snapshotPath),
    snapshotId: snapshot.snapshotId,
    status: snapshot.status,
    sha256: createHash("sha256").update(bytes).digest("hex"),
  },
}, null, 2) + "\n";

await emit("phase-three-metrics.tex", metrics);
await emit("phase-three-pruning-table.tex", table);
await emit("phase-three-snapshot-manifest.json", manifest);
console.log(`${checkOnly ? "Checked" : "Generated"} Phase Three article evidence.`);
