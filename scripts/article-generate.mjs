import {createHash} from "node:crypto";
import {readFile, readdir, mkdir, writeFile} from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const article = path.join(root, "article");
const generated = path.join(article, "generated");
const checkOnly = process.argv.includes("--check");

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function tex(value) {
  return String(value)
      .replaceAll("\\", "\\textbackslash{}")
      .replaceAll("&", "\\&")
      .replaceAll("%", "\\%")
      .replaceAll("_", "\\_")
      .replaceAll("#", "\\#")
      .replaceAll("$", "\\$");
}

function command(name, value) {
  return `\\newcommand{\\${name}}{${value}}`;
}

async function loadApprovedSnapshots() {
  const index = JSON.parse(await readFile(path.join(article, "data", "index.json"), "utf8"));
  const snapshots = [];
  for (const entry of index.snapshots) {
    if (!entry.approved) continue;
    const filePath = path.join(article, "data", entry.file);
    const bytes = await readFile(filePath);
    const data = JSON.parse(bytes.toString("utf8"));
    if (data.schemaVersion !== 1 || !data.snapshotId || !data.provenance) {
      throw new Error(`Invalid evidence snapshot: ${entry.file}`);
    }
    snapshots.push({file: entry.file, bytes, sha256: sha256(bytes), data});
  }
  if (snapshots.length !== 1) {
    throw new Error(`The v0.1 generator expects exactly one approved snapshot; found ${snapshots.length}.`);
  }
  return snapshots;
}

function generatedFiles(snapshot) {
  const d = snapshot.data;
  const td = d.phaseOne.openingTimeToDepth;
  const metric = (seconds, mode, key) => td.find((x) => x.seconds === seconds && x.mode === mode)[key];
  const p = d.pilot.aggregate;
  const lines = [
    "% Generated by scripts/article-generate.mjs. Do not edit.",
    command("PaperSnapshotId", tex(d.snapshotId)),
    command("ProductionMask", d.provenance.productionExperimentMask),
    command("EmscriptenVersion", tex(d.provenance.emscriptenVersion)),
    command("ParityPositions", `\\num{${d.validation.randomPositions}}`),
    command("PhaseOneOldFiveSecondSelectiveDepth", metric(5, "selective", "before")),
    command("PhaseOneNewFiveSecondSelectiveDepth", metric(5, "selective", "after")),
    command("PhaseOneOldFiveSecondVerifiedDepth", metric(5, "verified", "before")),
    command("PhaseOneNewFiveSecondVerifiedDepth", metric(5, "verified", "after")),
    command("PhaseOneOldFifteenSecondSelectiveDepth", metric(15, "selective", "before")),
    command("PhaseOneNewFifteenSecondSelectiveDepth", metric(15, "selective", "after")),
    command("ColdExpectedMoveDepth", d.phaseTwo.persistence.coldExpectedMoveDepth),
    command("WarmExpectedMoveDepth", d.phaseTwo.persistence.warmExpectedMoveDepth),
    command("ExpectedMoveReusedNodes", `\\num{${d.phaseTwo.persistence.expectedMoveReusedNodes}}`),
    command("SamePositionReusedNodes", `\\num{${d.phaseTwo.persistence.samePositionReusedNodes}}`),
    command("DynamicRootSingleMs", `\\num{${d.phaseTwo.dynamicRoot.singleWorkerMs}}`),
    command("DynamicRootEightMs", `\\num{${d.phaseTwo.dynamicRoot.eightWorkerMs}}`),
    command("DynamicRootSpeedup", d.phaseTwo.dynamicRoot.speedup),
    command("DynamicRootEfficiency", d.phaseTwo.dynamicRoot.efficiencyPercent),
    command("PilotGames", `\\num{${p.games}}`),
    command("PilotHybridWins", `\\num{${p.hybridWins}}`),
    command("PilotExhaustiveWins", `\\num{${p.exhaustiveWins}}`),
    command("PilotUnresolved", `\\num{${p.unresolved}}`),
    command("PilotPlies", `\\num{${p.plies}}`),
    command("PilotAveragePlies", p.averagePlies.toFixed(2)),
    command("PilotScheduledJobs", d.environment.pilotScheduledJobs),
    command("EngineMemoryMiB", d.environment.engineMemoryBudgetMiB),
    command("ZeroWallStates", `\\num{${d.solvers.zeroWallStates}}`),
    command("LowWallStateCeiling", `\\num{${d.solvers.oneTotalWallStateCeiling}}`),
    ""
  ].join("\n");

  const timeCsv = ["case,before,after", ...td.map((x) => `${x.seconds}s-${x.mode},${x.before},${x.after}`), ""].join("\n");
  const workerCsv = ["workers,nps", ...d.phaseOne.parallel.map((x) => `${x.workers},${x.aggregateNps}`), ""].join("\n");
  const pilotCsv = [
    "color,hybrid,exhaustive",
    `periwinkle,${p.hybridWinsPeriwinkle},${p.exhaustiveWinsPeriwinkle}`,
    `blossom,${p.hybridWinsBlossom},${p.exhaustiveWinsBlossom}`,
    ""
  ].join("\n");

  const pilotRows = d.pilot.controls.map((x) =>
    `${x.moveTimeMs} ms & ${x.games} & ${x.hybridWins} & ${x.exhaustiveWins} & ${x.unresolved} & ${x.averagePlies.toFixed(2)} & ${tex(x.sprt)} \\\\`).join("\n");
  const pilotTable = `% Generated file.\n\\begin{table}[h]\n\\centering\n\\caption{Preliminary pilot by move-time control.}\n\\label{tab:pilot-detail}\n\\scriptsize\n\\begin{tabular}{rrrrrrl}\n\\toprule\nLimit & Games & Hybrid & Exhaust. & Unres. & Avg. ply & SPRT \\\\ \n\\midrule\n${pilotRows}\n\\bottomrule\n\\end{tabular}\n\\end{table}\n`;

  const experimentRows = d.experiments.map((x) =>
    `${tex(x.name)} & ${tex(x.status)} & ${tex(x.result)} \\\\`).join("\n");
  const experimentsTable = `% Generated file.\n\\begin{table*}[t]\n\\centering\n\\caption{Versioned search and evaluation experiments. Held means parity passed but strength evidence is insufficient.}\n\\label{tab:experiments}\n\\scriptsize\n\\begin{tabular}{p{0.23\\textwidth}p{0.09\\textwidth}p{0.58\\textwidth}}\n\\toprule\nExperiment & Status & Recorded result \\\\ \n\\midrule\n${experimentRows}\n\\bottomrule\n\\end{tabular}\n\\end{table*}\n`;

  const related = `% Generated file.\n\\begin{table*}[t]\n\\centering\n\\caption{Public Quoridor search projects considered in the literature review. Evidence is not directly comparable across projects.}\n\\label{tab:related-work}\n\\scriptsize\n\\begin{tabular}{p{0.16\\textwidth}p{0.08\\textwidth}p{0.16\\textwidth}p{0.18\\textwidth}p{0.25\\textwidth}p{0.07\\textwidth}}\n\\toprule\nProject & Board & Language & Search & Published evidence & License \\\\ \n\\midrule\nGlendenning~\\cite{glendenning2005} & 9$\\times$9 & Java & iterative alpha--beta & thesis methodology; no modern common benchmark & thesis \\\\
Dais--Prentzas~\\cite{dais2023} & 9$\\times$9 & C & alpha--beta, TT & competition winner; no NPS/depth protocol & MIT \\\\
Gorisanson~\\cite{gorisanson2024} & 9$\\times$9 & JavaScript & heuristic MCTS & rollout counts and paired match tables & MIT \\\\
Borowski~\\cite{borowski2021} & 9$\\times$9 & C++ & vanilla MCTS & qualitative competence; no common benchmark & repository license \\\\
Slatton~\\cite{slatton2026solver} & reduced & Rust & proof search, retrograde & reproducible solved small boards; 9$\\times$9 out of scope & MIT \\\\
\\walwuk{} & 9$\\times$9 & C++/Wasm & hybrid alpha--beta & parity, time-to-depth, root audits, preliminary self-play & MIT \\\\ \n\\bottomrule\n\\end{tabular}\n\\end{table*}\n`;

  const manifest = JSON.stringify({
    schemaVersion: 1,
    generatedBy: "scripts/article-generate.mjs",
    snapshots: [{file: snapshot.file, snapshotId: d.snapshotId, status: d.status, sha256: snapshot.sha256}]
  }, null, 2) + "\n";

  return new Map([
    ["metrics.tex", lines],
    ["time-to-depth.csv", timeCsv],
    ["worker-scaling.csv", workerCsv],
    ["pilot-wins.csv", pilotCsv],
    ["pilot-table.tex", pilotTable],
    ["experiments-table.tex", experimentsTable],
    ["related-work-table.tex", related],
    ["snapshot-manifest.json", manifest]
  ].map(([name, content]) => [name, content.replaceAll(" \n", "\n")]));
}

async function main() {
  const snapshots = await loadApprovedSnapshots();
  const files = generatedFiles(snapshots[0]);
  await mkdir(generated, {recursive: true});
  const stale = [];
  for (const [name, content] of files) {
    const output = path.join(generated, name);
    if (checkOnly) {
      let current = "";
      try { current = await readFile(output, "utf8"); } catch { current = ""; }
      if (current !== content) stale.push(name);
    } else {
      await writeFile(output, content, "utf8");
    }
  }
  if (checkOnly && stale.length) {
    throw new Error(`Generated article files are stale: ${stale.join(", ")}`);
  }
  const dataFiles = (await readdir(path.join(article, "data"))).filter((x) => x.endsWith(".json"));
  console.log(`${checkOnly ? "Checked" : "Generated"} ${files.size} files from ${snapshots.length} approved snapshot; ${dataFiles.length} JSON files tracked.`);
}

await main();
